--comment: CLOUD-1038: add delete triggers to cleanup automatic FW.IP_GROUP and dependent members
CREATE OR REPLACE PROCEDURE FW.DELETE_AUTO_IP_GROUPS (
    P_IP_GROUP_ID_1 IN FW.IP_GROUP.ID%TYPE,
    P_IP_GROUP_ID_2 IN FW.IP_GROUP.ID%TYPE DEFAULT NULL,
    P_IP_GROUP_ID_3 IN FW.IP_GROUP.ID%TYPE DEFAULT NULL
) AS
    L_IP_GROUP_IDS SYS.ODCINUMBERLIST;
    L_SCOPED_MEMBER_IDS SYS.ODCINUMBERLIST;
BEGIN
    SELECT DISTINCT IG.ID
    BULK COLLECT INTO L_IP_GROUP_IDS
    FROM FW.IP_GROUP IG
    JOIN (
        SELECT P_IP_GROUP_ID_1 AS ID FROM DUAL
        UNION ALL SELECT P_IP_GROUP_ID_2 FROM DUAL
        UNION ALL SELECT P_IP_GROUP_ID_3 FROM DUAL
    ) P ON P.ID = IG.ID
    WHERE P.ID IS NOT NULL
      AND IG.AUTOMATIC = 1;

    IF L_IP_GROUP_IDS.COUNT = 0 THEN
        RETURN;
    END IF;

    SELECT DISTINCT IGM.SCOPED_IP_GROUP_MEMBER_ID
    BULK COLLECT INTO L_SCOPED_MEMBER_IDS
    FROM FW.IP_GROUP_MEMBER IGM
    WHERE IGM.SCOPED_IP_GROUP_MEMBER_ID IS NOT NULL
      AND IGM.IP_GROUP_ID IN (SELECT COLUMN_VALUE FROM TABLE(L_IP_GROUP_IDS));

    DELETE FROM FW.IP_GROUP_MEMBER
    WHERE IP_GROUP_ID IN (SELECT COLUMN_VALUE FROM TABLE(L_IP_GROUP_IDS));

    DELETE FROM FW.IP_GROUP
    WHERE ID IN (SELECT COLUMN_VALUE FROM TABLE(L_IP_GROUP_IDS));

    IF L_SCOPED_MEMBER_IDS.COUNT = 0 THEN
        RETURN;
    END IF;

    DELETE FROM FW.SCOPED_IP_GROUP_MEMBER
    WHERE ID IN (SELECT COLUMN_VALUE FROM TABLE(L_SCOPED_MEMBER_IDS));
END;
