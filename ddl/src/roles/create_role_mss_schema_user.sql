CREATE ROLE "MSS_SCHEMA_USER";
 GRANT
    CREATE TRIGGER,
    CREATE PROCEDURE,
    CREATE SEQUENCE,
    CREATE VIEW,
    CREATE SYNONYM,
    CREATE TABLE,
    ALTER SESSION,
    CREATE SESSION,
    DROP PUBLIC SYNONYM,
    CREATE PUBLIC SYNONYM
  TO "MSS_SCHEMA_USER";

