CREATE MATERIALIZED VIEW LOG ON mss.interface WITH ROWID,PRIMARY KEY (host_id) INCLUDING NEW VALUES;
CREATE MATERIALIZED VIEW LOG ON vpn.vpn_member WITH ROWID,PRIMARY KEY (partition_id, interface_id) INCLUDING NEW VALUES;
