-- migration/pgsql/_support/pgmig_name_rewrite.sql
--
-- In-database counterpart of migration/mapping/rewrite_names.py: Oracle object names
-- are not only referenced from code, they are STORED IN DATA and resolved at run time
-- (the "dynamically fabricated" calls). In the TT closure these are:
--
--   tt.event_action.procedure_name      'tt.escalation_interface.escalate_os'
--   mss.key.string_default              keys tt.event-action.* (ids 139, 140, 399)
--   mss.key.regexp                      '^tt\.escalation_interface\.(nop|escalate_(customer|os))$'
--   mss.value.string_value              per-host overrides of those keys
--
-- tt.event_interface_exec_event_type_actions reads these, splits on '.', and
-- dispatches through an allowlist (migration/spec/DYNAMIC-SQL-TRACE.md). The values
-- therefore have to be rewritten to the PostgreSQL 2-part names once, at data-load
-- time -- the same mapping, the same rules (R1 three-part, R2 dynamic prefix, R3
-- synonym), expressed as a SQL function so it can run inside the migration
-- transaction and be re-run idempotently.
--
-- Objects (schema pgmig = "PostgreSQL migration support", not an Oracle schema):
--   pgmig.oracle_name_map           the mapping rows (loaded by pgmig_name_map_data.sql,
--                                   GENERATED by rewrite_names.py --emit-sql)
--   pgmig.rewrite_oracle_names(text) pure function: rewrites every known name in a text
--   pgmig.apply_data_name_rewrites() procedure: rewrites the known columns above and
--                                   returns a row per (table, column, rows_changed)
--
-- Not a translated Oracle package: lives under _support/ which provenance_lint.sh
-- exempts (there is no Oracle original to be spec-first about).

CREATE SCHEMA IF NOT EXISTS pgmig;

CREATE TABLE IF NOT EXISTS pgmig.oracle_name_map (
    oracle_name text PRIMARY KEY,          -- lower-case 'schema.package.object', 'synonym.object'
                                           -- or 'schema.package.' (dynamic prefix)
    pg_name     text NOT NULL,             -- 'schema.package_object' or 'schema.package_' prefix
    kind        text NOT NULL CHECK (kind IN ('routine', 'synonym', 'dynamic_prefix')),
    pg_kind     text NOT NULL DEFAULT ''   -- 'procedure' | 'function' | '' (prefix rows)
);
COMMENT ON TABLE pgmig.oracle_name_map IS
    'Oracle -> PostgreSQL object-name map, generated from migration/mapping/name-map.csv by '
    'rewrite_names.py --emit-sql. Consumed by pgmig.rewrite_oracle_names().';

-- Rewrites every Oracle three-part / synonym / dynamic-prefix name found in p_text.
-- Longest names first so a prefix never shadows a full name; case-insensitive; a
-- backslash-escaped dot (regex stored in data) is accepted as a separator and the
-- first separator keeps its escaping. Returns p_text unchanged when nothing matches
-- (NULL in, NULL out).
CREATE OR REPLACE FUNCTION pgmig.rewrite_oracle_names(p_text text)
RETURNS text
LANGUAGE plpgsql
STABLE
AS $fn$
DECLARE
    r       RECORD;
    v_text  text := p_text;
    v_parts text[];
    v_pat   text;
    v_rep   text;
BEGIN
    IF v_text IS NULL OR v_text = '' THEN
        RETURN v_text;
    END IF;
    FOR r IN
        SELECT oracle_name, pg_name, kind
        FROM pgmig.oracle_name_map
        ORDER BY CASE kind WHEN 'routine' THEN 0 WHEN 'synonym' THEN 1 ELSE 2 END,
                 length(oracle_name) DESC, oracle_name
    LOOP
        v_parts := string_to_array(r.oracle_name, '.');
        IF r.kind = 'dynamic_prefix' THEN
            -- 'schema.package.'  ->  'schema.package_'  (keep the first separator as written,
            -- require the cut to sit before a quote, '(', '||' or end of text)
            v_pat := '(?<![A-Za-z0-9_"])' || v_parts[1] || '(\\?\.)' || v_parts[2]
                     || '\\?\.(?=\s*([''"(]|\|\||$))';
            v_rep := split_part(r.pg_name, '.', 1) || '\1' || split_part(r.pg_name, '.', 2);
        ELSIF r.kind = 'synonym' THEN
            v_pat := '(?<![A-Za-z0-9_".])' || v_parts[1] || '\s*\\?\.\s*' || v_parts[2] || '(?![A-Za-z0-9_"])';
            v_rep := r.pg_name;
        ELSE
            v_pat := '(?<![A-Za-z0-9_"])' || v_parts[1] || '\s*(\\?\.)\s*' || v_parts[2]
                     || '\s*\\?\.\s*' || v_parts[3] || '(?![A-Za-z0-9_"])';
            v_rep := split_part(r.pg_name, '.', 1) || '\1' || split_part(r.pg_name, '.', 2);
        END IF;
        v_text := regexp_replace(v_text, v_pat, v_rep, 'gi');
    END LOOP;
    RETURN v_text;
END;
$fn$;

-- Applies pgmig.rewrite_oracle_names() to every column known to hold Oracle object
-- names at run time. Idempotent: already-rewritten values contain no Oracle names and
-- are left alone. Returns one row per column touched.
CREATE OR REPLACE FUNCTION pgmig.apply_data_name_rewrites()
RETURNS TABLE (table_name text, column_name text, rows_changed bigint)
LANGUAGE plpgsql
AS $fn$
DECLARE
    v_n bigint;
BEGIN
    UPDATE tt.event_action
       SET procedure_name = pgmig.rewrite_oracle_names(procedure_name)
     WHERE procedure_name IS DISTINCT FROM pgmig.rewrite_oracle_names(procedure_name);
    GET DIAGNOSTICS v_n = ROW_COUNT;
    table_name := 'tt.event_action'; column_name := 'procedure_name'; rows_changed := v_n; RETURN NEXT;

    UPDATE mss.key
       SET string_default = pgmig.rewrite_oracle_names(string_default)
     WHERE string_default IS DISTINCT FROM pgmig.rewrite_oracle_names(string_default);
    GET DIAGNOSTICS v_n = ROW_COUNT;
    table_name := 'mss.key'; column_name := 'string_default'; rows_changed := v_n; RETURN NEXT;

    UPDATE mss.key
       SET regexp = pgmig.rewrite_oracle_names(regexp)
     WHERE regexp IS DISTINCT FROM pgmig.rewrite_oracle_names(regexp);
    GET DIAGNOSTICS v_n = ROW_COUNT;
    table_name := 'mss.key'; column_name := 'regexp'; rows_changed := v_n; RETURN NEXT;

    UPDATE mss.value
       SET string_value = pgmig.rewrite_oracle_names(string_value)
     WHERE string_value IS DISTINCT FROM pgmig.rewrite_oracle_names(string_value);
    GET DIAGNOSTICS v_n = ROW_COUNT;
    table_name := 'mss.value'; column_name := 'string_value'; rows_changed := v_n; RETURN NEXT;
END;
$fn$;
