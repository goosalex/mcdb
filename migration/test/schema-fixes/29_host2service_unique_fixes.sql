-- The Oracle export carries a UNIQUE index on MSS.HOST2SERVICE(HOST_ID):
--
--   ddl/generated/schema.oracle.sql:3700
--     CREATE UNIQUE INDEX MSS.IDX_H2S_HOST_UN ON MSS.HOST2SERVICE(HOST_ID);
