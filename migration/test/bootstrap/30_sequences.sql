-- migration/test/bootstrap/30_sequences.sql
--
-- Ports ddl/generated/sequences/*.sql (30 files, Oracle syntax -- ora2pg's
-- ddl/migrated/ ships ZERO `CREATE SEQUENCE` statements anywhere; every one of
-- these sequences is an ora2pg gap, not a translation). Ported here rather than
-- edited in place (D-P7): the source ddl/generated/ files are untouched.
--
-- The only Oracle-only clause found across all 30 files is `ORDER` (guarantees
-- monotonic RAC-wide ordering; PostgreSQL has no RAC and no equivalent clause,
-- and a single-instance sequence is already monotonic per session/cache, so it
-- is simply dropped). `START WITH n` is valid PostgreSQL syntax unchanged (5
-- sequences use it: NIDS x4 at 5000000000, STOP.CONTACT_SEQ at 1000,
-- STOP.COMPANY_SEQ at 700). No NOCACHE / NOCYCLE / MINVALUE / MAXVALUE clauses
-- were found in any of the 30 files (verified by grep across the full set).
--
-- Unquoted identifiers fold to lowercase automatically (matching every other
-- object in this schema, e.g. tt.event_sequence, auth.seq_profile) -- including
-- MSS.ISEQ$$_852069, whose `$$` is a valid (if unusual) PostgreSQL identifier
-- character in a non-leading position, not a dollar-quote delimiter here.
--
-- Ported ALL 30 files, not just the pilot's 12 (tt.event_sequence,
-- tt.ticket_sequence, tt.ticketflow_seq, tt.changerequest_seq,
-- tt.ticketdocspage_seq, tt.ticketrating_seq, tt.todoitem_seq,
-- tt.ticketreqclassification_seq, tt.tickettimestatistic_seq, auth.seq_profile,
-- auth.seq_user_company_scope, auth.seq_user_permission) -- cheap, and Phase 5
-- needs them anyway (plan's explicit instruction).

