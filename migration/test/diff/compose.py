#!/usr/bin/env python3
"""migration/test/diff/compose.py -- build the one-shot script a scenario runs on one side.

Python 3.12, stdlib only. Called by run-diff.sh; usable by hand to inspect what a
scenario will send to SQL*Plus or psql:

  compose.py --dialect ora --scenario scenarios/tt__event_interface__ticket_type
  compose.py --dialect pg  --scenario scenarios/...  [--pg-timezone UTC]

Scenario directory contents (see README.md):

  meta.env            ORA_USER=, COMMITS=no|yes, COMPARE_MSG=no|yes, DEFER_CONSTRAINTS=yes|no,
                      DESCRIPTION=
  setup.sql           dialect-neutral fixtures (optional); setup.ora.sql / setup.pg.sql override
  call.ora.sql        the routine invocations, SQL*Plus syntax (PL/SQL blocks end with `/`)
  call.pg.sql         the same invocations, psql syntax (DO $$ ... $$;)
  probe.sql           dialect-neutral SELECTs, each ending in `;` on its own line end and
                      each with ORDER BY; probe.ora.sql / probe.pg.sql override. A comment
                      line `-- probe: <label>` right before a statement labels its section.
  cleanup.ora.sql     COMMITS=yes only: best-effort removal of committed rows on Oracle
  known.diff          optional: the +/- lines of a difference that is understood and
                      accepted (documented ORACLE-BUG deviations); see run-diff.sh

Both scripts create the probe table `diff_probe(step, code, msg, n, s)` BEFORE the
scenario's own statements and run setup -> call -> probes inside one transaction that
ends with ROLLBACK (COMMITS=no), so Oracle is left untouched.

Oracle specifics (why the Oracle script looks the way it does):
  - CREATE TABLE is a committing DDL in Oracle, so the probe table is a GLOBAL TEMPORARY
    TABLE created before the transaction starts (nothing to commit at that point) and
    dropped after the ROLLBACK. Its rows are session-private and transactional.
  - SET MARKUP CSV ON makes every SELECT print RFC-4180-ish CSV with an upper-case
    header; FEEDBACK OFF removes "N rows selected." and -- for an empty result -- the
    header as well (normalize.py rule R8 absorbs that).
  - NUMWIDTH 40 keeps 20-digit NUMBERs (IPv6 halves) out of scientific notation.
  - SQLBLANKLINES ON lets PL/SQL blocks contain blank lines; DEFINE OFF stops `&` from
    prompting; WHENEVER SQLERROR CONTINUE makes a failing statement data (ORA- line in the
    stream), not an abort -- matching psql's ON_ERROR_STOP=0.
  - SET CONSTRAINTS ALL DEFERRED is issued on both sides (unless DEFER_CONSTRAINTS=no):
    every FK in ddl/generated/constraints.oracle.sql is DEFERRABLE, and the pgTAP fixtures
    rely on deferral; keeping both sides identical here is what makes the fixtures portable.

PostgreSQL specifics:
  - `\\set ON_ERROR_ROLLBACK on` makes psql wrap each statement in a savepoint, so a
    failing statement does not poison the rest of the transaction -- Oracle's
    statement-level atomicity, emulated.
  - The probe table is a TEMP table ON COMMIT DROP inside the transaction.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from normalize import read_meta  # noqa: E402

PROBE_DDL_COLUMNS_ORA = "step VARCHAR2(100), code VARCHAR2(20), msg VARCHAR2(4000), n NUMBER, s VARCHAR2(4000)"
PROBE_DDL_COLUMNS_PG = "step varchar(100), code varchar(20), msg varchar(4000), n numeric, s varchar(4000)"

ORA_PREAMBLE = f"""\
-- generated by migration/test/diff/compose.py -- Oracle side
SET ECHO OFF
SET TERMOUT ON
SET FEEDBACK OFF
SET VERIFY OFF
SET DEFINE OFF
SET SQLBLANKLINES ON
SET SERVEROUTPUT OFF
SET HEADING ON
SET PAGESIZE 50000
SET LINESIZE 32767
SET LONG 100000
SET LONGCHUNKSIZE 100000
SET TRIMOUT ON
SET TRIMSPOOL ON
SET NUMWIDTH 40
SET MARKUP CSV ON DELIMITER , QUOTE ON
WHENEVER SQLERROR CONTINUE
WHENEVER OSERROR CONTINUE
ALTER SESSION SET NLS_DATE_FORMAT = 'YYYY-MM-DD HH24:MI:SS';
ALTER SESSION SET NLS_TIMESTAMP_FORMAT = 'YYYY-MM-DD HH24:MI:SS.FF6';
ALTER SESSION SET NLS_TIMESTAMP_TZ_FORMAT = 'YYYY-MM-DD HH24:MI:SS.FF6 TZR';
ALTER SESSION SET NLS_NUMERIC_CHARACTERS = '.,';
-- probe table: a session-private GTT, created before the transaction (DDL commits)
BEGIN
    EXECUTE IMMEDIATE 'CREATE GLOBAL TEMPORARY TABLE diff_probe ({PROBE_DDL_COLUMNS_ORA}) ON COMMIT PRESERVE ROWS';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;  -- -955: already exists (stale from an aborted run)
END;
/
"""

ORA_POSTAMBLE_ROLLBACK = """\
ROLLBACK;
"""

ORA_DROP_PROBE = """\
TRUNCATE TABLE diff_probe;
-- The GTT definition is deliberately NOT dropped: it is one object per Oracle user, its ROWS are
-- session-private, and dropping it here pulled it from under a concurrent run of another
-- scenario connected as the same user (ORA-00942 mid-run, seen 2026-10-21 with several agents
-- running as SYSTEM). The empty definition is the one artifact a run leaves behind on Oracle.
EXIT ROLLBACK
"""

PG_PREAMBLE = """\
-- generated by migration/test/diff/compose.py -- PostgreSQL side
\\set ON_ERROR_ROLLBACK on
SET client_min_messages = warning;
SET datestyle = 'ISO, YMD';
SET timezone = '{tz}';
"""


def pick(scenario: Path, base: str, dialect: str, required: bool) -> Path | None:
    specific = scenario / f"{base}.{dialect}.sql"
    if specific.exists():
        return specific
    neutral = scenario / f"{base}.sql"
    if neutral.exists():
        return neutral
    if required:
        raise SystemExit(f"compose.py: {scenario.name}: missing {base}.{dialect}.sql / {base}.sql")
    return None


def read(path: Path | None) -> str:
    if path is None:
        return ""
    text = path.read_text(encoding="utf-8")
    return text if text.endswith("\n") else text + "\n"


PROBE_LABEL_RE = re.compile(r"^\s*--\s*probe:\s*(.+?)\s*$")


def split_probes(text: str) -> list[tuple[str, str]]:
    """Split probe.sql into (label, statement) pairs. A statement ends at a line whose
    last non-blank character is `;`. Comment-only lines are dropped except for the
    `-- probe: label` form, which labels the statement that follows."""
    probes: list[tuple[str, str]] = []
    label = ""
    current: list[str] = []
    for line in text.splitlines():
        stripped = line.strip()
        if not current and not stripped:
            continue
        if stripped.startswith("--"):
            m = PROBE_LABEL_RE.match(line)
            if m and not current:
                label = m.group(1)
            continue
        current.append(line.rstrip())
        if stripped.endswith(";"):
            probes.append((label, "\n".join(current)))
            label = ""
            current = []
    if current:
        raise SystemExit("compose.py: probe file ends with a statement that has no terminating ';'")
    return probes


def marker(n: int, label: str) -> str:
    return f"## probe {n}" + (f" {label}" if label else "")


def compose_ora(scenario: Path, meta: dict[str, str]) -> str:
    commits = meta.get("COMMITS", "no").lower() == "yes"
    defer = meta.get("DEFER_CONSTRAINTS", "yes").lower() != "no"
    out = [ORA_PREAMBLE]
    if defer:
        out.append("SET CONSTRAINTS ALL DEFERRED;\n")
    out.append("-- ---- setup ----\n" + read(pick(scenario, "setup", "ora", required=False)))
    out.append("-- ---- call ----\n" + read(pick(scenario, "call", "ora", required=True)))
    out.append("-- ---- probes ----\n")
    for i, (label, stmt) in enumerate(split_probes(read(pick(scenario, "probe", "ora", required=True))), 1):
        out.append(f"PROMPT {marker(i, label)}\n{stmt}\n")
    if commits:
        # The routine committed on its own; the ROLLBACK below only undoes what is still
        # pending. cleanup.ora.sql is the author's best effort to remove committed rows.
        out.append(ORA_POSTAMBLE_ROLLBACK)
        cleanup = scenario / "cleanup.ora.sql"
        if cleanup.exists():
            out.append("-- ---- cleanup (COMMITS=yes) ----\n" + read(cleanup) + "COMMIT;\n")
    else:
        out.append(ORA_POSTAMBLE_ROLLBACK)
    out.append(ORA_DROP_PROBE)
    return "".join(out)


def compose_pg(scenario: Path, meta: dict[str, str], tz: str) -> str:
    commits = meta.get("COMMITS", "no").lower() == "yes"
    defer = meta.get("DEFER_CONSTRAINTS", "yes").lower() != "no"
    out = [PG_PREAMBLE.format(tz=tz)]
    if commits:
        # No transaction block: a PL/pgSQL procedure may COMMIT only when called outside
        # one. The database is a fresh clone for this scenario (run-diff.sh).
        out.append(f"CREATE TEMP TABLE diff_probe ({PROBE_DDL_COLUMNS_PG});\n")
    else:
        out.append("BEGIN;\n")
        out.append(f"CREATE TEMP TABLE diff_probe ({PROBE_DDL_COLUMNS_PG}) ON COMMIT DROP;\n")
        if defer:
            out.append("SET CONSTRAINTS ALL DEFERRED;\n")
    out.append("-- ---- setup ----\n" + read(pick(scenario, "setup", "pg", required=False)))
    out.append("-- ---- call ----\n" + read(pick(scenario, "call", "pg", required=True)))
    out.append("-- ---- probes ----\n")
    for i, (label, stmt) in enumerate(split_probes(read(pick(scenario, "probe", "pg", required=True))), 1):
        out.append(f"\\echo {marker(i, label)}\n{stmt}\n")
    if commits:
        out.append("DROP TABLE diff_probe;\n")
    else:
        out.append("ROLLBACK;\n")
    return "".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dialect", choices=("ora", "pg"), required=True)
    parser.add_argument("--scenario", type=Path, required=True)
    parser.add_argument("--pg-timezone", default="UTC")
    parser.add_argument("--count-probes", action="store_true", help="print the number of probe statements and exit")
    args = parser.parse_args(argv)

    scenario = args.scenario
    if not scenario.is_dir():
        raise SystemExit(f"compose.py: not a scenario directory: {scenario}")
    meta = read_meta(scenario / "meta.env")
    if args.count_probes:
        print(len(split_probes(read(pick(scenario, "probe", args.dialect, required=True)))))
        return 0
    if args.dialect == "ora":
        sys.stdout.write(compose_ora(scenario, meta))
    else:
        sys.stdout.write(compose_pg(scenario, meta, args.pg_timezone))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
