#!/usr/bin/env bash
# migration/test/diff/derive_pg_call.sh -- draft call.pg.sql from call.ora.sql.
#
# THIS IS A HELPER, NOT A TRANSLATOR. It saves the scenario author the mechanical part
# of writing the PostgreSQL twin of an Oracle call script; the output MUST be reviewed
# and usually edited (PL/pgSQL has no nested procedures, no OUT-parameter-less CALL of a
# procedure with OUT arguments without declaring variables, no implicit RETURN from a
# block, different exception names, ...). It never touches the scenario directory; it
# writes to stdout.
#
# Usage:
#   derive_pg_call.sh scenarios/<name>/call.ora.sql > /tmp/call.pg.sql.draft
#
# What it applies, in order:
#   1. migration/mapping/client-rename.sed -- the GNU sed script that
#      migration/mapping/rewrite_names.py --emit-sed generates from name-map.csv. It
#      rewrites three-part routine references (TT.TICKET_INTERFACE.change_status ->
#      tt.ticket_interface_change_status) and public-synonym references
#      (OSAG_IP.ip2num -> mss.osag_ip_ip2num). It is applied exactly as its header says:
#      `sed -E -f client-rename.sed` (case-insensitive patterns, GNU sed). Bare
#      same-schema references (R4) are NOT covered -- qualify them in call.ora.sql.
#   2. CALL for procedures: a statement line that starts with a pg_name whose pg_kind is
#      `procedure` in migration/mapping/client-rename-map.csv gets `CALL ` in front.
#   3. Block syntax: a top-level `DECLARE` or `BEGIN` opens `DO $$ DECLARE`/`DO $$ BEGIN`;
#      the SQL*Plus terminator line `/` becomes `$$;`.
#   4. Built-ins: SYSDATE -> now(); `FROM DUAL` removed; <seq>.NEXTVAL -> nextval('<seq>');
#      TO_CHAR(SQLCODE) / SQLCODE -> SQLSTATE; VARCHAR2 -> varchar; SUBSTR( -> substr(;
#      NVL( -> coalesce(; CHR(10) -> E'\n'.
#
# Requires GNU sed (gsed on macOS).
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
MAPPING_DIR="$(cd "${SCRIPT_DIR}/../../mapping" && pwd)"
RENAME_SED="${MAPPING_DIR}/client-rename.sed"
RENAME_CSV="${MAPPING_DIR}/client-rename-map.csv"

[[ $# -eq 1 && -f "$1" ]] || { echo "usage: $0 call.ora.sql > call.pg.sql.draft" >&2; exit 1; }
SED=sed
if command -v gsed >/dev/null 2>&1; then SED=gsed; fi

step1() {
  if [[ -f "$RENAME_SED" ]]; then
    "$SED" -E -f "$RENAME_SED"
  else
    echo "derive_pg_call.sh: ${RENAME_SED} not found -- regenerate with rewrite_names.py --emit-sed; names left as-is" >&2
    cat
  fi
}

# Build a sed script that prefixes CALL to procedure invocations (step 2).
CALL_SED="$(mktemp)"
trap 'rm -f "$CALL_SED"' EXIT
if [[ -f "$RENAME_CSV" ]]; then
  awk -F, 'NR > 1 && $1 == "routine" && $4 == "procedure" { print $3 }' "$RENAME_CSV" \
    | sort -u \
    | "$SED" -E 's/[.]/\\./g; s|^(.*)$|s/^([[:space:]]*)(\1)[[:space:]]*\\(/\\1CALL \\2(/I|' > "$CALL_SED"
fi

step2() { "$SED" -E -f "$CALL_SED"; }

step3_4() {
  "$SED" -E \
    -e '/^DECLARE[[:space:]]*$/{s/^DECLARE/DO $$ DECLARE/I;x;s/^$/seen/;x}' \
    -e '/^BEGIN[[:space:]]*$/{x;/^$/{x;s/^BEGIN/DO $$ BEGIN/I;x;s/^$/seen/;x;b};x}' \
    -e 's|^/[[:space:]]*$|$$;|' \
    -e 's/\bSYSDATE\b/now()/Ig' \
    -e 's/[[:space:]]+FROM[[:space:]]+DUAL\b//Ig' \
    -e "s/\b([a-z_][a-z0-9_]*(\.[a-z_][a-z0-9_]*)?)\.NEXTVAL\b/nextval('\1')/Ig" \
    -e 's/TO_CHAR\(SQLCODE\)/SQLSTATE/Ig' \
    -e 's/\bSQLCODE\b/SQLSTATE/Ig' \
    -e 's/\bVARCHAR2\b/varchar/Ig' \
    -e 's/\bSUBSTR\(/substr(/Ig' \
    -e 's/\bNVL\(/coalesce(/Ig' \
    -e "s/\bCHR\(10\)/E'\\\\n'/Ig"
}

{
  echo "-- DRAFT generated by migration/test/diff/derive_pg_call.sh from $(basename "$1") -- REVIEW BEFORE USE."
  echo "-- Nested PL/SQL procedures must become pg_temp.* functions; OUT parameters need declared variables."
  step1 < "$1" | step2 | step3_4
}
