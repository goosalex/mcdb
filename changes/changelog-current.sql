--changeset jkl:2657
--comment: Populate VPN.T2EE_CONTACT from the Partner Connect tables VPN.PARTNER_CONTACT and VPN.PARTNER_LOCATION
INSERT INTO VPN.T2EE_CONTACT (ID, COMPANY_ID, NAME, EMAIL, PHONE, ADDRESS, PARTNER_CONTACT_ID, PARTNER_PHASE1_ID)
SELECT VPN.T2EE_CONTACT_SEQUENCE.NEXTVAL,
       src.COMPANY_ID,
       src.NAME,
       src.EMAIL,
       src.PHONE,
       src.ADDRESS,
       src.PARTNER_CONTACT_ID,
       src.PARTNER_PHASE1_ID
  FROM (SELECT p1.CUSTOMER_COMPANY_ID AS COMPANY_ID,
               c.CONTACT_NAME         AS NAME,
               c.CONTACT_EMAIL        AS EMAIL,
               c.CONTACT_PHONE        AS PHONE,
               loc.ADDRESS            AS ADDRESS,
               c.ID                   AS PARTNER_CONTACT_ID,
               p1.ID                  AS PARTNER_PHASE1_ID
          FROM VPN.PARTNER_CONTACT c
          JOIN VPN.PARTNER_PHASE1 p1 ON p1.ID = c.PARTNER_PHASE1_ID
          LEFT JOIN (SELECT PARTNER_PHASE1_ID, MIN(ADDRESS) AS ADDRESS
                       FROM VPN.PARTNER_LOCATION
                      GROUP BY PARTNER_PHASE1_ID) loc ON loc.PARTNER_PHASE1_ID = p1.ID) src;

